'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),vm=require('node:vm');
const base=path.join(__dirname,'..');
const php=fs.readFileSync(path.join(base,'agas-design-studio.php'),'utf8');
const script=fs.readFileSync(path.join(base,'assets','studio.js'),'utf8');
const qr=fs.readFileSync(path.join(base,'assets','vendor','agas-qrcode.js'),'utf8');
assert(php.includes("const VERSION = '0.1.16'"));
const ids=new Set([...php.matchAll(/\bid="([a-zA-Z0-9_-]+)"/g)].map(x=>x[1]));
const refs=new Set([...script.matchAll(/\$\(['"](agas-[^'"]+)['"]\)/g)].map(x=>x[1]));
for(const id of refs) assert(ids.has(id),'Missing editor control: '+id);
for(const id of ['agas-add-subheading','agas-clipart-grid','agas-clipart-category','agas-add-qr','agas-qr-url','agas-bg-file','agas-bg-remove','agas-template-title','agas-template-status','agas-protect-delete','agas-thumb-front','agas-thumb-back','agas-bleed','agas-guide-vertical','agas-zoom-select','agas-help-open']) assert(ids.has(id),id);
const googleFonts=['Inter','Roboto','Open Sans','Lato','Montserrat','Poppins','Oswald','Merriweather','Raleway','Nunito','Playfair Display','Source Sans 3'];
for(const font of googleFonts) assert(php.includes('<option>'+font+'</option>'),'Missing font option '+font);
const categoryCounts={business:0,events:0,nature:0,symbols:0};
const area=script.slice(script.indexOf('var cliparts=['),script.indexOf('  function svgMarkup(paths)'));
for (const hit of area.matchAll(/\['(business|events|nature|symbols)','[^']+'/g)) categoryCounts[hit[1]]++;
assert.deepEqual(categoryCounts,{business:6,events:6,nature:6,symbols:6});
assert(php.includes("'adminTemplateMode' => (bool) $admin_template_mode"));
assert(php.includes("'post_status' => $requested_status"));
assert(script.includes('selected.agasAdminLocked && !cfg.adminTemplateMode'));
const context={};context.globalThis=context;vm.runInNewContext(qr,context);
const rows=context.AGAS_QR.create('https://example.com/design/41');
assert(rows.length>=21&&rows.every(r=>r.length===rows.length));
console.log('PASS 24 original cliparts across 4 categories');
console.log('PASS 12 Google Fonts and advanced editor controls');
console.log('PASS QR generation local module');
console.log('PASS admin template and protected objects code contract');
console.log('PASS editor HTML/JavaScript control IDs');
console.log('EDITOR_FEATURE_TESTS=PASS');
