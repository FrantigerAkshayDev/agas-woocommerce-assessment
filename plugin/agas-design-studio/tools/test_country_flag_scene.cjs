/* v0.1.15: approved civic-plaza country flag, without touching feather flags. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const code=fs.readFileSync(path.join(root,'assets/realistic-mockups.js'),'utf8');
const php=fs.readFileSync(path.join(root,'agas-design-studio.php'),'utf8');
const pluginHeaderVersion = php.match(/\* Version:\s*([0-9]+\.[0-9]+\.[0-9]+)/)?.[1];
assert(pluginHeaderVersion && php.includes(`const VERSION = '${pluginHeaderVersion}';`));
const context={window:{},document:{},WeakMap,Promise};
vm.runInNewContext(code,context);
const mockups=context.window.AGASRealisticMockups;
const nation=mockups.scenes['flag-rectangular'];
const business=mockups.scenes['flag-feather'];
assert.equal(nation.kind,'flag');
assert.equal(nation.fabric,true);
assert.equal(nation.photo,'flag-rectangular.jpg');
assert.match(nation.label,/civic plaza/);
assert.equal(business.feather,true);
assert.equal(business.photo,'flag.jpg');
assert.equal(mockups.resolve('flag','Country Flags','Japan Flag'),'flag-rectangular');
assert.equal(mockups.resolve('flag','Country Flags','France Flag'),'flag-rectangular');
assert.equal(mockups.resolve('flag','Business','Company Brand Flag'),'flag-feather');
const photo=path.join(root,'assets/mockups/photos/flag-rectangular.jpg');
assert(fs.statSync(photo).size>120000,'approved photo is bundled');
assert.match(code,/ctx\.globalCompositeOperation='multiply'/,'fabric shading retained');
assert.match(code,/if\(scene\.fabric\)\{/,'custom cloth clipping and mesh enabled');
assert.match(code,/if\(scene\.folds && !scene\.fabric\)/,'no artificial straight fold lines');
console.log('PASS country flags use approved civic-plaza scene and woven fabric shading');
console.log('PASS country flags keep landscape shape; business feather flag unchanged');
console.log('COUNTRY_FLAG_SCENE_TESTS=PASS');
